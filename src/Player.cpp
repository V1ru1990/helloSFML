//////////////////////////////////////////////////////////////////////////////////////////
Player::Player()
    : m_x(DEFAULT_PLAYER_X)
    , m_y(DEFAULT_PLAYER_Y)
    , m_width(DEFAULT_PLAYER_WIDTH)
    , m_height(DEFAULT_PLAYER_HEIGHT)
    , m_textureLoaded(false)
{

}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::loadTexture(const char* filename) //загрузка текстуры 
//с последующей подгрузкой спрайта
{
    m_texturePlayer.loadFromFile(filename);
    m_textureLoaded = true;
    m_spritePlayer.setTexture(m_texturePlayer);
}
