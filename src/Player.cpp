#include <SFML/Graphics.hpp>
#include "Engine/Constants.h"
#include "Engine/Player.h"

#include <iostream>

//////////////////////////////////////////////////////////////////////////////////////////
Player::Player()
    : m_x(DEFAULT_PLAYER_X)
    , m_y(DEFAULT_PLAYER_Y)
    , m_dx(0)
    , m_dy(0)
    , m_width(DEFAULT_PLAYER_WIDTH)
    , m_height(DEFAULT_PLAYER_HEIGHT)
    , m_textureLoaded(false)
    , m_isOnGround(false)
{

}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::loadTexture(const char* filename) //загрузка текстуры 
//с последующей подгрузкой спрайта
{
    if (m_texturePlayer.loadFromFile(filename))
    {
        m_textureLoaded = true;
        std::cerr << "Texture loaded from " << filename << std::endl;
    }
    else
    {
        std::cerr << "Texture loading error\n";
        m_textureLoaded = false;
        return;
    }
    m_spritePlayer.setTexture(m_texturePlayer);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::update(float gravity) //перемещние по оси ординат
{
    m_gravity = gravity;
    m_dy += m_gravity;
    m_x += m_dx;
    m_y += m_dy;

    /////проверка горизонтальной границы
    if (m_x < 0)
    {
        m_x = 0;
        m_dx = 0;
    }

    if (m_x > WINDOW_LENGTH - m_width)
    {
        m_x = WINDOW_LENGTH - m_width;
        m_dx = 0;
    }
    /////

    /////проверка на земле ли объект
    if (m_y >= WINDOW_WIDTH - m_height)
    {
        m_y = WINDOW_WIDTH - m_height;
        m_dy = 0;
        m_isOnGround = true;
    }

    else
    {
        m_isOnGround = false;
    }

    m_spritePlayer.setPosition(m_x, m_y);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::stopHorizontal() //остановка скорости по абсциссе
{
    m_dx = 0;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::handleInput() //проверяем нажатие клавиши 
{
    if (sf::Keyboard::isKeyPressed(sf::Keyboard::Left))
    {
        Player::moveLeft();
    }

    else if(sf::Keyboard::isKeyPressed(sf::Keyboard::Right))
    {
        Player::moveRight();
    }

    else
    {
        Player::stopHorizontal();
    }

    if (sf::Keyboard::isKeyPressed(sf::Keyboard::Space) && !isFalling())
    {
        jump(DEFAULT_JUMP_POWER);
    }

}
//////////////////////////////////////////////////////////////////////////////////////////
void Player::moveLeft() //перемещение влево по оси абсцисс
{
    m_dx = -DEFAULT_MOVE_SPEED;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::moveRight() //перемещение вправо по оси абсцисс
{
    m_dx = DEFAULT_MOVE_SPEED;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::jump(float jumpPower) //прыжок +
{
    if (!isFalling() && m_isOnGround)
    {
        m_dy = jumpPower;
        m_isOnGround = false;
    }
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::setPosition(float x, float y) //задание координат объекту
{
    m_x = x;
    m_y = y;
    m_spritePlayer.setPosition(m_x, m_y);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
sf::Vector2f Player::getPosition() const //получение координат
{
    return sf::Vector2f(m_x, m_y);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
sf::FloatRect Player::getBounds() const //получение прямоугольника для коллизии
{
    return sf::FloatRect(m_x, m_y, m_width, m_height);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::draw(sf::RenderWindow& window) //отрисока в окне 
{
    if(m_textureLoaded)
    {
        window.draw(m_spritePlayer);
    }
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
bool Player::isOnGround() const //возвращение значения
{
    return m_isOnGround;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
bool Player::isFalling() const //проверка на падение  
{
    return m_dy > 0.0f && !m_isOnGround;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
float Player::getX() const //геттер на абсциссу
{
    return m_x;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
float Player::getY() const //геттер на ординату
{
    return m_y;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
float Player::getDX() const //геттер на скорость по абсциссе
{
    return m_dx;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
float Player::getDY() const //геттер на скорость по ординате
{
    return m_dy;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::setX(float newX) //сеттер на абсциссу
{
    m_x = newX;
    m_spritePlayer.setPosition(m_x, m_y);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::setY(float newY) //сеттер на ординату
{
    m_y = newY;
    m_spritePlayer.setPosition(m_x, m_y);
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::setDX(float newDX) //сеттер на скорость по абсциссе
{
    m_dx = newDX;
}
//////////////////////////////////////////////////////////////////////////////////////////


//////////////////////////////////////////////////////////////////////////////////////////
void Player::setDY(float newDY) //сеттер скорости по ординате
{
    m_dy = newDY;
}
